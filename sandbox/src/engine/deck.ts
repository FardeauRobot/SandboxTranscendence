import { RANKS, SUIT_IDS, type Card } from './types';

/** RNG déterministe (mulberry32) : même seed → même donne, pour comparer deux réglages. */
export function makeRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function createDeck(): Card[] {
  const deck: Card[] = [];
  for (const suit of SUIT_IDS) for (const rank of RANKS) deck.push({ id: `${suit}-${rank}`, suit, rank });
  return deck;
}

export function shuffle<T>(items: readonly T[], rng: () => number): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

